/** Default (unthemed) Chrome in dark mode, for the main checkout's pill. */
export const DEFAULT_CHROME_THEME: InstanceTheme = { name: "default", seed: "#3c3c3c", toolbar: "#3c3c3c", frame: "#1f2020" };

const themeForPort = (port: number) => {
	const n = INSTANCE_THEMES.length;
	return INSTANCE_THEMES[(((port - PORT_MIN) % n) + n) % n];
};

const slotOf = (instance: string | undefined, port: number, profileDir: string): BrowserSlot => ({
	instance,
	port,
	url: `http://127.0.0.1:${port}`,
	profileDir,
	theme: instance ? themeForPort(port) : undefined,
	label: instance ?? "main",
});

function readPort(file: string): number | undefined {
	try {
		const n = Number(readFileSync(file, "utf8").trim());
		return Number.isInteger(n) && n > 0 ? n : undefined;
	} catch {
		return undefined;
	}
}

/** Browser for a target: the main one, or the instance's own (claiming a port on first use). */
export function browserSlot(instance?: string): BrowserSlot {
	if (!instance) return slotOf(undefined, MAIN_PORT, MAIN_PROFILE);
	const dir = join(INSTANCES_DIR, instance);
	const portFile = join(dir, "port");
	const profileDir = join(dir, "profile");
	const existing = readPort(portFile);
	if (existing) return slotOf(instance, existing, profileDir);

	mkdirSync(dir, { recursive: true });
	mkdirSync(PORTS_DIR, { recursive: true });
	for (let port = PORT_MIN; port <= PORT_MAX; port++) {
		if (port === MAIN_PORT) continue;
		const claim = join(PORTS_DIR, String(port));
		try {
			mkdirSync(claim); // atomic: fails if another instance owns this port
		} catch {
			continue;
		}
		writeFileSync(join(claim, "owner"), instance);
		try {
			writeFileSync(portFile, String(port), { flag: "wx" });
		} catch {
			// Another pi claimed a port for this same instance at the same moment: use theirs.
			rmSync(claim, { recursive: true, force: true });
			const theirs = readPort(portFile);
			if (theirs) return slotOf(instance, theirs, profileDir);
			continue;
		}
		return slotOf(instance, port, profileDir);
	}
	throw new Error(`No free browser debugging port in ${PORT_MIN}-${PORT_MAX}. Remove stale entries in ${PORTS_DIR}.`);
}

const CHROME_CANDIDATES = [
	process.env.PI_BROWSER_CHROME_PATH,
	"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
	"/usr/bin/google-chrome",
	"/usr/bin/google-chrome-stable",
	"/usr/bin/chromium",
].filter((p): p is string => !!p);

export async function isChromeUp(slot: BrowserSlot): Promise<boolean> {
	try {
		const res = await fetch(`${slot.url}/json/version`, { signal: AbortSignal.timeout(1000) });
		return res.ok;
	} catch {
		return false;
	}
}

type Prefs = Record<string, unknown>;

const obj = (o: Prefs, key: string): Prefs => {
	const v = o[key];
	if (v && typeof v === "object" && !Array.isArray(v)) return v as Prefs;
	return (o[key] = {});
};

const AUTOGENERATED_THEME_ID = "autogenerated_theme_id";

/** "#rrggbb" -> Chrome's SkColor pref value (opaque ARGB as a signed 32-bit int). */
const skColor = (hex: string) => (0xff000000 | Number.parseInt(hex.slice(1), 16)) | 0;

/**
 * Before launch (Chrome rewrites Preferences while running, so edit only when it's down):
 *  - first launch: keep the password manager from saving/offering the test credentials
 *  - every launch: apply the instance's color as Chrome's "autogenerated" theme (a fixed, saturated
 *    toolbar). The newer "Customize Chrome" user color is avoided: in dark mode Chrome mutes it to a
 *    near-gray that's hard to match, so any of its prefs (from earlier versions of this code) are removed.
 */
function prepareProfile(slot: BrowserSlot) {
	mkdirSync(join(slot.profileDir, "Default"), { recursive: true });
	const file = join(slot.profileDir, "Default", "Preferences");
	let prefs: Prefs | undefined;
	if (existsSync(file)) {
		if (!slot.theme) return;
		try {
			prefs = JSON.parse(readFileSync(file, "utf8")) as Prefs;
		} catch {
			return; // unreadable: leave it to Chrome rather than clobber the profile
		}
	} else {
		prefs = {
			credentials_enable_service: false,
			credentials_enable_autosignin: false,
			profile: { password_manager_enabled: false },
			autofill: { profile_enabled: false, credit_card_enabled: false },
		};
	}
	if (slot.theme) {
		const color = skColor(slot.theme.seed);
		const autogen = obj(obj(prefs, "autogenerated"), "theme");
		const ext = obj(obj(prefs, "extensions"), "theme");
		const userColor = obj(obj(prefs, "browser"), "theme");
		const stale = ["user_color", "user_color2", "color_variant", "color_variant2"].filter((k) => k in userColor);
		if (autogen.color === color && ext.id === AUTOGENERATED_THEME_ID && !stale.length) return;
		autogen.color = color;
		ext.id = AUTOGENERATED_THEME_ID;
		for (const k of stale) delete userColor[k];
	}
	writeFileSync(file, JSON.stringify(prefs));
}

async function launch(slot: BrowserSlot): Promise<void> {
	if (await isChromeUp(slot)) return;
	const exe = CHROME_CANDIDATES.find((p) => existsSync(p));
	if (!exe) throw new Error("Chrome executable not found. Set PI_BROWSER_CHROME_PATH.");
	try {
		prepareProfile(slot);
	} catch {
		// Cosmetic/first-run prefs only; never block the browser on them.
	}
	const child = spawn(
		exe,
		[
			`--remote-debugging-port=${slot.port}`,
			`--user-data-dir=${slot.profileDir}`,
			"--no-first-run",
			"--no-default-browser-check",
			"--hide-crash-restore-bubble",
			"--password-store=basic",
			// Fixed title for the first window (Mission Control, Window menu, Cmd-`) instead of the page title.
			`--window-name=RT ${slot.label}`,
			"about:blank",
		],
		{ detached: true, stdio: "ignore" },
	);
	child.unref();

	const deadline = Date.now() + 20_000;
	while (Date.now() < deadline) {
		if (await isChromeUp(slot)) return;
		await new Promise((r) => setTimeout(r, 250));
	}
	throw new Error(`Chrome did not open its debugging port ${slot.port} within 20s.`);
}

const starting = new Map<number, Promise<void>>();

/** Start the slot's Chrome if it is not already listening. Safe to call concurrently. */
export function ensureChrome(slot: BrowserSlot): Promise<void> {
	let p = starting.get(slot.port);
	if (!p) {
		p = launch(slot).finally(() => starting.delete(slot.port));
		starting.set(slot.port, p);
	}
	return p;
}

/** Close an instance's Chrome and delete its profile and port claim (for `rtw rm`). No-op for main. */
export async function releaseInstanceBrowser(instance: string): Promise<void> {
	const dir = join(INSTANCES_DIR, instance);
	if (!existsSync(dir)) return;
	const port = readPort(join(dir, "port"));
	if (port) {
		const slot = slotOf(instance, port, join(dir, "profile"));
		if (await isChromeUp(slot)) {
			const browser = await puppeteer.connect({ browserURL: slot.url }).catch(() => undefined);
			await browser?.close().catch(() => undefined);
			// close() returns before Chrome finishes writing its profile; wait for it to exit.
			const deadline = Date.now() + 10_000;
			while (Date.now() < deadline && (await isChromeUp(slot))) await new Promise((r) => setTimeout(r, 250));
		}
		const owner = join(PORTS_DIR, String(port), "owner");
		if (existsSync(owner) && readFileSync(owner, "utf8").trim() === instance) {
			rmSync(join(PORTS_DIR, String(port)), { recursive: true, force: true });
		}
	}
	rmSync(dir, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
}
